SET search_path = public;

-- =============================================================================
-- DMIS LAST-MILE FOUNDATION (Production-safe, additive, idempotent)
-- -----------------------------------------------------------------------------
-- Your operational rules:
--  - MAIN-HUB (Haining Rd, Pimento, etc): donation intake allowed
--  - SUB-HUB (LSA under ODPEM): donation intake NOT allowed
--  - HSA (JDF, MLSS, Parish Councils): donation intake allowed into their own warehouses
--  - LSA can dispatch to ANY HSA warehouse (no static LSA→HSA assignment)
--  - Last-mile module: HSA warehouse → Beneficiary (Shelter & Individual)
-- -----------------------------------------------------------------------------
-- IMPORTANT: No drops / renames. All changes are additive.
-- =============================================================================


-- =============================================================================
-- 1) CLASSIFY CUSTODIANS AS LSA OR HSA (additive column)
--    - ODPEM custodian stays as LSA (but can still have MAIN and SUB hubs)
--    - HSA custodians (JDF/MLSS/etc.) will be set to HSA
-- =============================================================================

ALTER TABLE public.custodian
  ADD COLUMN IF NOT EXISTS org_type varchar(10);

-- Default any existing custodian rows to LSA if org_type is null
UPDATE public.custodian
   SET org_type = COALESCE(org_type, 'LSA')
 WHERE org_type IS NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_custodian_org_type') THEN
    ALTER TABLE public.custodian
      ADD CONSTRAINT c_custodian_org_type
      CHECK (org_type IN ('LSA','HSA'));
  END IF;
END$$;


-- =============================================================================
-- 2) HSA MASTER TABLE (in-scope only: JDF, MLSS, Parish Councils, etc.)
--    - Uses custodian as the authoritative organization record.
--    - 1:1 relationship: each HSA is a custodian with org_type='HSA'
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.hsa (
    hsa_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    custodian_id  integer NOT NULL UNIQUE
      REFERENCES public.custodian(custodian_id) ON DELETE RESTRICT,

    hsa_code      varchar(30) NOT NULL UNIQUE,   -- e.g. JDF, MLSS, HSA_12 (for parish councils until refined)
    hsa_category  varchar(30) NOT NULL,          -- JDF, MLSS, PARISH_COUNCIL, OTHER
    status_code   char(1) NOT NULL DEFAULT 'A',
    notes         text,

    create_by_id  varchar(20) NOT NULL DEFAULT 'SYSTEM',
    create_dtime  timestamp(0) without time zone NOT NULL DEFAULT now(),
    update_by_id  varchar(20) NOT NULL DEFAULT 'SYSTEM',
    update_dtime  timestamp(0) without time zone NOT NULL DEFAULT now(),
    version_nbr   integer NOT NULL DEFAULT 1
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_hsa_code_upper') THEN
    ALTER TABLE public.hsa
      ADD CONSTRAINT c_hsa_code_upper CHECK (hsa_code = upper(hsa_code));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_hsa_category') THEN
    ALTER TABLE public.hsa
      ADD CONSTRAINT c_hsa_category CHECK (hsa_category IN ('JDF','MLSS','PARISH_COUNCIL','OTHER'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_hsa_status') THEN
    ALTER TABLE public.hsa
      ADD CONSTRAINT c_hsa_status CHECK (status_code IN ('A','I'));
  END IF;
END$$;

-- Helpful index for ownership lookups (HSA can have many warehouses via warehouse.custodian_id)
CREATE INDEX IF NOT EXISTS ix_warehouse_custodian ON public.warehouse(custodian_id);


-- =============================================================================
-- 2A) OPTIONAL SAFE SEEDING (non-breaking)
--    If custodians already exist for JDF/MLSS/Parish Councils, we can classify them.
--    This is "best effort": it only affects matching names and is safe to override later.
-- =============================================================================

-- Seed MLSS if present
INSERT INTO public.hsa (custodian_id, hsa_code, hsa_category, status_code, notes)
SELECT c.custodian_id, 'MLSS', 'MLSS', 'A', 'Seeded from custodian_name match'
FROM public.custodian c
WHERE c.custodian_name ILIKE '%MLSS%'
  AND NOT EXISTS (SELECT 1 FROM public.hsa h WHERE h.custodian_id = c.custodian_id);

-- Seed JDF if present
INSERT INTO public.hsa (custodian_id, hsa_code, hsa_category, status_code, notes)
SELECT c.custodian_id, 'JDF', 'JDF', 'A', 'Seeded from custodian_name match'
FROM public.custodian c
WHERE c.custodian_name ILIKE '%JDF%'
  AND NOT EXISTS (SELECT 1 FROM public.hsa h WHERE h.custodian_id = c.custodian_id);

-- Seed Parish Councils if present (unique code per custodian: HSA_<custodian_id>)
INSERT INTO public.hsa (custodian_id, hsa_code, hsa_category, status_code, notes)
SELECT c.custodian_id, ('HSA_' || c.custodian_id::text), 'PARISH_COUNCIL', 'A',
       'Seeded from custodian_name match; rename hsa_code later to parish-specific code'
FROM public.custodian c
WHERE c.custodian_name ILIKE '%PARISH%'
  AND c.custodian_name ILIKE '%COUNCIL%'
  AND NOT EXISTS (SELECT 1 FROM public.hsa h WHERE h.custodian_id = c.custodian_id);

-- Ensure custodians linked to HSA are marked org_type='HSA'
UPDATE public.custodian c
SET org_type = 'HSA'
WHERE EXISTS (SELECT 1 FROM public.hsa h WHERE h.custodian_id = c.custodian_id);


-- =============================================================================
-- 3) WAREHOUSE TIERING + DONATION INTAKE RULES (additive columns)
--    - MAIN-HUB = tier MAIN (ODPEM main hubs)
--    - SUB-HUB  = tier LSA  (ODPEM sub-hubs / LSA)
--    - Any warehouse owned by an HSA custodian = tier HSA
--    - Donation intake allowed for MAIN and HSA, not allowed for LSA
-- =============================================================================

ALTER TABLE public.warehouse
  ADD COLUMN IF NOT EXISTS warehouse_tier varchar(10);

ALTER TABLE public.warehouse
  ADD COLUMN IF NOT EXISTS allows_donation_intake boolean;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_warehouse_tier') THEN
    ALTER TABLE public.warehouse
      ADD CONSTRAINT c_warehouse_tier
      CHECK (warehouse_tier IS NULL OR warehouse_tier IN ('MAIN','LSA','HSA'));
  END IF;
END$$;

-- Owner-first tier assignment:
--  (1) If custodian is HSA -> warehouse tier = HSA
UPDATE public.warehouse w
SET warehouse_tier = 'HSA'
FROM public.custodian c
WHERE w.custodian_id = c.custodian_id
  AND c.org_type = 'HSA'
  AND (w.warehouse_tier IS NULL OR w.warehouse_tier <> 'HSA');

--  (2) Otherwise use warehouse_type mapping (ODPEM MAIN/SUB hubs)
UPDATE public.warehouse
SET warehouse_tier = CASE
  WHEN warehouse_type = 'MAIN-HUB' THEN 'MAIN'
  WHEN warehouse_type = 'SUB-HUB'  THEN 'LSA'
  ELSE warehouse_tier
END
WHERE warehouse_tier IS NULL
  AND warehouse_type IN ('MAIN-HUB','SUB-HUB');

-- Donation intake rule derived from tier (non-breaking; nullable allowed)
UPDATE public.warehouse
SET allows_donation_intake = CASE
  WHEN warehouse_tier IN ('MAIN','HSA') THEN TRUE
  WHEN warehouse_tier = 'LSA' THEN FALSE
  ELSE allows_donation_intake
END
WHERE allows_donation_intake IS NULL
  AND warehouse_tier IS NOT NULL;

-- Optional view for UI filters (safe)
CREATE OR REPLACE VIEW public.v_warehouse_intake_eligible AS
SELECT w.*
FROM public.warehouse w
WHERE w.status_code = 'A'
  AND w.allows_donation_intake = TRUE;


-- =============================================================================
-- 4) BENEFICIARY MASTER TABLE (single table: INDIVIDUAL or SHELTER)
--    - Individuals are created during HSA distribution workflow (registered_hsa_id)
--    - Shelters can be mapped from legacy agency(SHELTER) for smooth transition
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.beneficiary (
    beneficiary_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    beneficiary_type    varchar(12) NOT NULL,     -- INDIVIDUAL | SHELTER

    -- Display name used everywhere:
    --  - SHELTER: shelter name
    --  - INDIVIDUAL: full name (or "given + family")
    beneficiary_name    varchar(160) NOT NULL,

    -- Structured fields (primarily INDIVIDUAL)
    given_name          varchar(80),
    family_name         varchar(80),

    phone_no            varchar(20),
    email_text          varchar(100),

    parish_code         char(2),
    community_text      varchar(120),
    address1_text       varchar(255),
    address2_text       varchar(255),

    -- Captured by which HSA (important for last-mile workflow + visibility)
    registered_hsa_id   integer
      REFERENCES public.hsa(hsa_id) ON DELETE SET NULL,

    -- Transitional link to existing shelter agency (do NOT remove agency yet)
    shelter_agency_id   integer UNIQUE
      REFERENCES public.agency(agency_id) ON DELETE SET NULL,

    status_code         char(1) NOT NULL DEFAULT 'A',
    notes               text,

    create_by_id        varchar(20) NOT NULL DEFAULT 'SYSTEM',
    create_dtime        timestamp(0) without time zone NOT NULL DEFAULT now(),
    update_by_id        varchar(20) NOT NULL DEFAULT 'SYSTEM',
    update_dtime        timestamp(0) without time zone NOT NULL DEFAULT now(),
    version_nbr         integer NOT NULL DEFAULT 1
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_beneficiary_type') THEN
    ALTER TABLE public.beneficiary
      ADD CONSTRAINT c_beneficiary_type
      CHECK (beneficiary_type IN ('INDIVIDUAL','SHELTER'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_beneficiary_status') THEN
    ALTER TABLE public.beneficiary
      ADD CONSTRAINT c_beneficiary_status CHECK (status_code IN ('A','I'));
  END IF;

  -- Type-specific requirement:
  --  - INDIVIDUAL must have given_name and family_name
  --  - SHELTER must NOT have given_name/family_name
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_beneficiary_required_fields') THEN
    ALTER TABLE public.beneficiary
      ADD CONSTRAINT c_beneficiary_required_fields CHECK (
        (beneficiary_type = 'INDIVIDUAL' AND given_name IS NOT NULL AND family_name IS NOT NULL)
        OR
        (beneficiary_type = 'SHELTER' AND given_name IS NULL AND family_name IS NULL)
      );
  END IF;
END$$;

CREATE INDEX IF NOT EXISTS ix_beneficiary_type ON public.beneficiary(beneficiary_type);
CREATE INDEX IF NOT EXISTS ix_beneficiary_registered_hsa ON public.beneficiary(registered_hsa_id);

