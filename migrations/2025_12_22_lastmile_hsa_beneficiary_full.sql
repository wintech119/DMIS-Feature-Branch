-- =============================================================================
-- 7) VIEWS FOR REPORTING + UI FILTERS (safe)
-- =============================================================================

-- All warehouses belonging to HSAs (HSA can have many warehouses via custodian_id)
CREATE OR REPLACE VIEW public.v_hsa_warehouses AS
SELECT
  h.hsa_id,
  h.hsa_code,
  h.hsa_category,
  c.custodian_id,
  c.custodian_name,
  w.warehouse_id,
  w.warehouse_name,
  w.warehouse_type,
  w.warehouse_tier,
  w.allows_donation_intake,
  w.parish_code,
  w.status_code
FROM public.hsa h
JOIN public.custodian c ON c.custodian_id = h.custodian_id
JOIN public.warehouse  w ON w.custodian_id = c.custodian_id;

