-- =============================================================================
-- 5) LAST-MILE MODULE TABLES (HSA warehouse -> beneficiary)
--    These are new and do NOT interfere with existing distribution_package flows.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.lastmile_distribution (
    distribution_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    hsa_id              integer NOT NULL
      REFERENCES public.hsa(hsa_id) ON DELETE RESTRICT,

    warehouse_id        integer NOT NULL
      REFERENCES public.warehouse(warehouse_id) ON DELETE RESTRICT,

    beneficiary_id      integer NOT NULL
      REFERENCES public.beneficiary(beneficiary_id) ON DELETE RESTRICT,

    event_id            integer
      REFERENCES public.event(event_id) ON DELETE SET NULL,

    distribution_dtime  timestamp(0) without time zone NOT NULL DEFAULT now(),
    status_code         char(1) NOT NULL DEFAULT 'D',     -- D Draft | C Completed | V Verified | X Cancelled
    notes               text,

    create_by_id        varchar(20) NOT NULL DEFAULT 'SYSTEM',
    create_dtime        timestamp(0) without time zone NOT NULL DEFAULT now(),
    update_by_id        varchar(20) NOT NULL DEFAULT 'SYSTEM',
    update_dtime        timestamp(0) without time zone NOT NULL DEFAULT now(),

    verify_by_id        varchar(20),
    verify_dtime        timestamp(0) without time zone,

    version_nbr         integer NOT NULL DEFAULT 1
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_lastmile_dist_status') THEN
    ALTER TABLE public.lastmile_distribution
      ADD CONSTRAINT c_lastmile_dist_status CHECK (status_code IN ('D','C','V','X'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_lastmile_dist_verify_pair') THEN
    ALTER TABLE public.lastmile_distribution
      ADD CONSTRAINT c_lastmile_dist_verify_pair
      CHECK (
        (verify_by_id IS NULL AND verify_dtime IS NULL)
        OR
        (verify_by_id IS NOT NULL AND verify_dtime IS NOT NULL)
      );
  END IF;
END$$;

CREATE INDEX IF NOT EXISTS ix_lastmile_dist_hsa_date
  ON public.lastmile_distribution(hsa_id, distribution_dtime);

CREATE INDEX IF NOT EXISTS ix_lastmile_dist_beneficiary
  ON public.lastmile_distribution(beneficiary_id);

CREATE INDEX IF NOT EXISTS ix_lastmile_dist_warehouse
  ON public.lastmile_distribution(warehouse_id);


CREATE TABLE IF NOT EXISTS public.lastmile_distribution_item (
    distribution_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    distribution_id      integer NOT NULL
      REFERENCES public.lastmile_distribution(distribution_id) ON DELETE CASCADE,

    item_id              integer NOT NULL
      REFERENCES public.item(item_id) ON DELETE RESTRICT,

    batch_id             integer
      REFERENCES public.itembatch(batch_id) ON DELETE SET NULL,

    uom_code             character varying(25)
      REFERENCES public.unitofmeasure(uom_code) ON DELETE RESTRICT,

    qty                  numeric(12,2) NOT NULL,
    notes                text
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'c_lastmile_dist_item_qty') THEN
    ALTER TABLE public.lastmile_distribution_item
      ADD CONSTRAINT c_lastmile_dist_item_qty CHECK (qty > 0);
  END IF;
END$$;

CREATE INDEX IF NOT EXISTS ix_lastmile_item_dist
  ON public.lastmile_distribution_item(distribution_id);

CREATE INDEX IF NOT EXISTS ix_lastmile_item_item
  ON public.lastmile_distribution_item(item_id);

CREATE INDEX IF NOT EXISTS ix_lastmile_item_batch
  ON public.lastmile_distribution_item(batch_id);


